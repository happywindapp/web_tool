# Inline src/data-workbench (template + @include css/js/html) into one self-contained tools/data-workbench.html.
# Usage: pwsh scripts/build-data-workbench-single-file.ps1 [-Check]   (-Check: exit 1 if the built file is stale)
param([switch]$Check)
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root 'src/data-workbench'
$out = Join-Path $root 'tools/data-workbench.html'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Source([string]$rel) {
  $path = Join-Path $src $rel
  if (-not (Test-Path $path)) { throw "Include not found: $rel" }
  ([IO.File]::ReadAllText($path, $utf8) -replace '^﻿', '') -replace "`r`n", "`n"
}

function Expand-Includes([string]$text) {
  $pattern = '(?m)^[ \t]*(?:<!--|/\*|//)[ \t]*@include[ \t]+(\S+?)[ \t]*(?:-->|\*/)?[ \t]*$'
  [regex]::Replace($text, $pattern, [Text.RegularExpressions.MatchEvaluator]{
    param($m)
    $rel = $m.Groups[1].Value
    $body = Read-Source $rel
    if ($rel -like '*.js') {
      # "</script" would end the inline <script> early; "<script" could start a nested one.
      if ($body -match '(?i)<script') { throw "$rel contains '<script' - cannot inline safely" }
      $body = [regex]::Replace($body, '(?i)</script', '<\/script')
    }
    if ($rel -like '*.html') { $body = Expand-Includes $body }
    $body.TrimEnd("`n")
  })
}

$html = Expand-Includes (Read-Source 'data-workbench.template.html')
$notice = "<!-- GENERATED by scripts/build-data-workbench-single-file.ps1 from src/data-workbench/ - do not edit this file directly. -->`n"
$html = $html -replace '(?i)^(<!doctype html>\n)', "`$1$notice"

if ($Check) {
  $current = if (Test-Path $out) { [IO.File]::ReadAllText($out, $utf8) } else { '' }
  if ($current -ne $html) { Write-Host 'STALE: tools/data-workbench.html differs from src/ - run the build.'; exit 1 }
  Write-Host 'OK: tools/data-workbench.html is up to date.'
  exit 0
}

[IO.File]::WriteAllText($out, $html, $utf8)
Write-Host ("Built tools/data-workbench.html ({0:N0} KB)" -f ((Get-Item $out).Length / 1KB))
