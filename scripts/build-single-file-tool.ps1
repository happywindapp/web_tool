# Inline src/<tool> (template + @include css/js/html) into one self-contained tools/<tool>.html.
# Usage: pwsh scripts/build-single-file-tool.ps1 [-Tool <name>] [-Check]   (no -Tool: every src/<x>/<x>.template.html — tools share modules; -Check: exit 1 if stale)
param([string]$Tool, [switch]$Check)
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Source([string]$src, [string]$rel) {
  $path = Join-Path $src $rel
  if (-not (Test-Path $path)) { throw "Include not found: $rel" }
  ([IO.File]::ReadAllText($path, $utf8) -replace '^﻿', '') -replace "`r`n", "`n"
}

function Expand-Includes([string]$src, [string]$text) {
  $pattern = '(?m)^[ \t]*(?:<!--|/\*|//)[ \t]*@include[ \t]+(\S+?)[ \t]*(?:-->|\*/)?[ \t]*$'
  [regex]::Replace($text, $pattern, [Text.RegularExpressions.MatchEvaluator]{
    param($m)
    $rel = $m.Groups[1].Value
    $body = Read-Source $src $rel
    if ($rel -like '*.js') {
      # "</script" would end the inline <script> early; "<script" could start a nested one.
      if ($body -match '(?i)<script') { throw "$rel contains '<script' - cannot inline safely" }
      $body = [regex]::Replace($body, '(?i)</script', '<\/script')
    }
    if ($rel -like '*.html') { $body = Expand-Includes $src $body }
    $body.TrimEnd("`n")
  })
}

# Returns $true when tools/<name>.html is (or now is) up to date.
function Build-Tool([string]$name) {
  $src = Join-Path $root "src/$name"
  $out = Join-Path $root "tools/$name.html"
  $html = Expand-Includes $src (Read-Source $src "$name.template.html")
  $notice = "<!-- GENERATED by scripts/build-single-file-tool.ps1 -Tool $name from src/$name/ - do not edit this file directly. -->`n"
  $html = $html -replace '(?i)^(<!doctype html>\n)', "`$1$notice"
  if ($Check) {
    $current = if (Test-Path $out) { [IO.File]::ReadAllText($out, $utf8) } else { '' }
    if ($current -ne $html) { Write-Host "STALE: tools/$name.html differs from src/ - run the build."; return $false }
    Write-Host "OK: tools/$name.html is up to date."
    return $true
  }
  [IO.File]::WriteAllText($out, $html, $utf8)
  Write-Host ("Built tools/$name.html ({0:N0} KB)" -f ((Get-Item $out).Length / 1KB))
  return $true
}

$names = if ($Tool) { @($Tool) } else {
  Get-ChildItem (Join-Path $root 'src') -Directory | Where-Object { Test-Path (Join-Path $_.FullName "$($_.Name).template.html") } | ForEach-Object Name
}
$ok = $true
foreach ($n in $names) { if (-not (Build-Tool $n)) { $ok = $false } }
if (-not $ok) { exit 1 }
