# Inline src/<tool> (template + @include css/js/html) into one self-contained tools/<tool>.html.
# Usage: pwsh scripts/build-single-file-tool.ps1 [-Tool <name>] [-Check]   (no -Tool: every src/<x>/<x>.template.html — tools share modules; -Check: exit 1 if stale)
param([string]$Tool, [switch]$Check)
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Source([string]$src, [string]$rel) {
  $path = Join-Path $src $rel
  if (-not (Test-Path $path)) { throw "Include not found: $rel" }
  ([IO.File]::ReadAllText($path, $utf8) -replace '^﻿', '') -replace "`r`n", "`n"
}

# $ext: the page being built; a .css included by a lazily loaded .js becomes a <style> added when that script runs.
function Expand-Includes([string]$src, [string]$text, [string]$ext = 'html') {
  $pattern = '(?m)^[ \t]*(?:<!--|/\*|//)[ \t]*@include[ \t]+(\S+?)[ \t]*(?:-->|\*/)?[ \t]*$'
  [regex]::Replace($text, $pattern, [Text.RegularExpressions.MatchEvaluator]{
    param($m)
    $rel = $m.Groups[1].Value
    $body = Read-Source $src $rel
    if ($rel -like '*.css' -and $ext -eq 'js') { return 'document.head.append(Object.assign(document.createElement("style"), { textContent: ' + (ConvertTo-Json $body.TrimEnd("`n") -Compress) + ' }));' }
    if ($rel -like '*.js') {
      # "</script" would end the inline <script> early; "<script" could start a nested one.
      if ($body -match '(?i)<script') { throw "$rel contains '<script' - cannot inline safely" }
      $body = [regex]::Replace($body, '(?i)</script', '<\/script')
    }
    if ($rel -like '*.html') { $body = Expand-Includes $src $body }
    $body.TrimEnd("`n")
  })
}

# A tool folder may hold extra pages: src/<tool>/<page>.template.html → tools/<page>.html, and lazily loaded scripts: <x>.template.js → tools/<x>.js (includes resolve from src/<tool>/).
function Build-Tool([string]$name) {
  $ok = $true
  $templates = Get-ChildItem (Join-Path $root "src/$name") -File | Where-Object Name -match '\.template\.(html|js)$' | Sort-Object { $_.Name -ne "$name.template.html" }, Name
  foreach ($t in $templates) {
    $null = $t.Name -match '^(.+)\.template\.(html|js)$'
    if (-not (Build-Page $name $Matches[1] $Matches[2])) { $ok = $false }
  }
  return $ok
}

# Returns $true when tools/<page>.<ext> is (or now is) up to date.
function Build-Page([string]$name, [string]$page, [string]$ext = 'html') {
  $src = Join-Path $root "src/$name"
  $out = Join-Path $root "tools/$page.$ext"
  $html = Expand-Includes $src (Read-Source $src "$page.template.$ext") $ext
  if ($ext -eq 'js') { $html = "// GENERATED by scripts/build-single-file-tool.ps1 -Tool $name from src/$name/ - do not edit this file directly.`n" + $html }
  else {
    $notice = "<!-- GENERATED by scripts/build-single-file-tool.ps1 -Tool $name from src/$name/ - do not edit this file directly. -->`n"
    $html = $html -replace '(?i)^(<!doctype html>\n)', "`$1$notice"
  }
  if ($Check) {
    $current = if (Test-Path $out) { [IO.File]::ReadAllText($out, $utf8) } else { '' }
    if ($current -ne $html) { Write-Host "STALE: tools/$page.$ext differs from src/ - run the build."; return $false }
    Write-Host "OK: tools/$page.$ext is up to date."
    return $true
  }
  [IO.File]::WriteAllText($out, $html, $utf8)
  Write-Host ("Built tools/$page.$ext ({0:N0} KB)" -f ((Get-Item $out).Length / 1KB))
  return $true
}

$names = if ($Tool) { @($Tool) } else {
  Get-ChildItem (Join-Path $root 'src') -Directory | Where-Object { Test-Path (Join-Path $_.FullName "$($_.Name).template.html") } | ForEach-Object Name
}
$ok = $true
foreach ($n in $names) { if (-not (Build-Tool $n)) { $ok = $false } }
if (-not $ok) { exit 1 }
